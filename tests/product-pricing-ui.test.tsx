function addAttributePlan(optionName: string, reference: EntityReference, name: string, base = '0', tier = '0', bind = true) {
  const area = currentArea()
  const id = `test-price-${area.additionalPricePlans.reduce((count, plan) => count + plan.prices.length, 0) + 1}`
  const template = area.templates[0]
  const plan = {
    areaAttributePriceId: id, optionName, reference, areaTemplateId: template.areaTemplateId,
    basePrice: base, tierPrices: template.tiers.map(row => ({ areaTierId: row.areaTierId, price: tier })),
  }
  const binding = area.categoryAdditionalPlanBindings.find(row => row.categoryId === 'keychains')
  let scheme = bind ? area.additionalPricePlans.find(row => row.additionalPricePlanId === binding?.additionalPricePlanId) : undefined
  if (!scheme) {
    scheme = { additionalPricePlanId: `test-plan-${area.additionalPricePlans.length + 1}`, name, prices: [] }
    area.additionalPricePlans.push(scheme)
    if (bind) {
      area.categoryAdditionalPlanBindings = area.categoryAdditionalPlanBindings.filter(row => row.categoryId !== 'keychains')
      area.categoryAdditionalPlanBindings.push({ categoryId: 'keychains', additionalPricePlanId: scheme.additionalPricePlanId })
    }
  }
  scheme.prices.push(plan)
  return { plan, scheme, template }
}

