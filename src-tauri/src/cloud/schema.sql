CREATE TABLE IF NOT EXISTS `user` (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(120) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY user_name(name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS pf_records (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  kind VARCHAR(24) NOT NULL,
  record_key VARCHAR(190) NOT NULL,
  owner_id BIGINT UNSIGNED NULL,
  version BIGINT UNSIGNED NOT NULL,
  name VARCHAR(512) NOT NULL DEFAULT '',
  saved_at VARCHAR(40) NOT NULL,
  status VARCHAR(24) NOT NULL DEFAULT '',
  source_review_id BIGINT UNSIGNED NULL,
  summary JSON NOT NULL,
  payload JSON NOT NULL,
  UNIQUE KEY record_identity(kind,record_key),
  UNIQUE KEY one_production_per_review(source_review_id),
  KEY list_owner(kind,owner_id,saved_at),
  KEY list_public(kind,status,saved_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS pf_resources (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  hash CHAR(64) NOT NULL UNIQUE,
  relative_path VARCHAR(1024) NOT NULL,
  bytes BIGINT UNSIGNED NOT NULL,
  released_at TIMESTAMP(3) NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS pf_resource_refs (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  record_id BIGINT UNSIGNED NOT NULL,
  resource_id BIGINT UNSIGNED NOT NULL,
  UNIQUE KEY record_resource(record_id,resource_id),
  KEY by_resource(resource_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS pf_requests (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  request_key CHAR(36) NOT NULL UNIQUE,
  user_id BIGINT UNSIGNED NOT NULL,
  digest CHAR(64) NOT NULL,
  response JSON NOT NULL,
  created_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS pf_transfers (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  request_id BIGINT UNSIGNED NOT NULL UNIQUE,
  batch_id BIGINT UNSIGNED NULL,
  batch_key VARCHAR(190) NOT NULL,
  from_user BIGINT UNSIGNED NOT NULL,
  to_user BIGINT UNSIGNED NOT NULL,
  transferred_at TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
CREATE TABLE IF NOT EXISTS pf_migrations (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  installation_key CHAR(36) NOT NULL,
  kind VARCHAR(24) NOT NULL,
  local_key VARCHAR(190) NOT NULL,
  cloud_id BIGINT UNSIGNED NULL,
  cloud_key VARCHAR(190) NOT NULL,
  UNIQUE KEY migration_source(installation_key,kind,local_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_bin;
